import { useEffect, useMemo, useState } from "react";
import { Button, Chip, Input, Select, SelectItem, Spinner } from "@nextui-org/react";
import { Copy, Download, Search } from "lucide-react";
import useApiCallUtils from "@/hooks/useApiCallUtils";

type Endpoint = { method: string; path: string; auth: string; tag: string; params: string[]; upload: boolean };

const METHOD_COLOR: Record<string, "success" | "primary" | "warning" | "danger" | "default"> = {
    GET: "success", POST: "primary", PUT: "warning", PATCH: "warning", DELETE: "danger",
};
const AUTH_LABEL: Record<string, string> = {
    public: "Public", agency: "Agency login", student: "Student login", admin: "Admin login", "local-dev-only": "Local dev only",
};
const AUTH_COLOR: Record<string, "default" | "secondary" | "success" | "danger" | "warning"> = {
    public: "warning", agency: "secondary", student: "success", admin: "danger", "local-dev-only": "default",
};

/** API reference generated by the server from its live routes (admin only). */
const SaasApiDocs = () => {
    const { commonGetAPICalls } = useApiCallUtils();
    const [spec, setSpec] = useState<any>(null);
    const [loading, setLoading] = useState(true);
    const [q, setQ] = useState("");
    const [auth, setAuth] = useState("all");

    useEffect(() => {
        (async () => {
            const { success, data } = await commonGetAPICalls("/saas_admin/api_docs");
            if (success) setSpec(data);
            setLoading(false);
        })();
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, []);

    const endpoints: Endpoint[] = spec?.["x-endpoints"] || [];
    const groups = useMemo(() => {
        const term = q.trim().toLowerCase();
        const list = endpoints.filter((e) =>
            (auth === "all" || e.auth === auth) && (!term || `${e.method} ${e.path}`.toLowerCase().includes(term)));
        const map = new Map<string, Endpoint[]>();
        for (const e of list) map.set(e.tag, [...(map.get(e.tag) || []), e]);
        return [...map.entries()].sort((a, b) => a[0].localeCompare(b[0]));
    }, [endpoints, q, auth]);
    const shown = groups.reduce((n, [, l]) => n + l.length, 0);

    const download = () => {
        const { ["x-endpoints"]: _omit, ...openapi } = spec || {};
        const url = URL.createObjectURL(new Blob([JSON.stringify(openapi, null, 2)], { type: "application/json" }));
        const a = document.createElement("a");
        a.href = url;
        a.download = `techx-crm-openapi-${openapi?.info?.version || "latest"}.json`;
        a.click();
        URL.revokeObjectURL(url);
    };
    const base = spec?.servers?.[0]?.url || "";

    if (loading) return <div className="flex justify-center py-20"><Spinner /></div>;
    if (!spec) return <div className="p-6 text-default-500">Could not load the API docs.</div>;

    return (
        <div className="space-y-5 p-4 md:p-6">
            <div className="flex flex-wrap items-start justify-between gap-3">
                <div>
                    <h1 className="text-2xl font-semibold">API docs</h1>
                    <p className="text-sm text-default-500">
                        {endpoints.length} endpoints, read from the running server. Send logins as <code>Authorization: Bearer &lt;token&gt;</code>;
                        student portal calls also send <code>x-agency-uuid</code>. Errors usually come back as HTTP 200 with <code>success: false</code>.
                    </p>
                </div>
                <Button color="primary" startContent={<Download size={16} />} onPress={download}>
                    OpenAPI JSON
                </Button>
            </div>

            <div className="flex flex-wrap gap-3">
                <Input className="max-w-md" placeholder="Search path or method, e.g. crm/leads or POST" value={q}
                    onValueChange={setQ} startContent={<Search size={16} className="text-default-400" />} isClearable onClear={() => setQ("")} />
                <Select aria-label="Login" className="max-w-[200px]" selectedKeys={[auth]}
                    onChange={(e) => setAuth(e.target.value || "all")}>
                    {[["all", "All logins"], ...Object.entries(AUTH_LABEL)].map(([k, v]) => <SelectItem key={k}>{v}</SelectItem>)}
                </Select>
                <span className="self-center text-sm text-default-500">{shown} shown</span>
            </div>

            {groups.map(([tag, list]) => (
                <section key={tag} className="rounded-xl border border-default-200">
                    <h2 className="border-b border-default-200 px-4 py-2 font-medium">/{tag} <span className="text-default-400">({list.length})</span></h2>
                    <ul className="divide-y divide-default-100">
                        {list.map((e) => (
                            <li key={`${e.method} ${e.path}`} className="flex flex-wrap items-center gap-2 px-4 py-2">
                                <Chip size="sm" variant="flat" color={METHOD_COLOR[e.method] || "default"} className="w-16 justify-center font-mono">{e.method}</Chip>
                                <code className="min-w-0 flex-1 break-all text-sm">{e.path}</code>
                                {e.upload && <Chip size="sm" variant="bordered">file upload</Chip>}
                                <Chip size="sm" variant="flat" color={AUTH_COLOR[e.auth] || "default"}>{AUTH_LABEL[e.auth] || e.auth}</Chip>
                                <Button isIconOnly size="sm" variant="light" aria-label="Copy URL"
                                    onPress={() => navigator.clipboard?.writeText(`${base}${e.path}`)}>
                                    <Copy size={14} />
                                </Button>
                            </li>
                        ))}
                    </ul>
                </section>
            ))}
            {!shown && <p className="text-default-500">No endpoints match.</p>}
        </div>
    );
};

export default SaasApiDocs;
